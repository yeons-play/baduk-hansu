// 기초 강의 데이터 — 7살 기준. 쉬운 말 먼저, 바둑 용어는 괄호로.
// 정답(숨구멍·집·차례·놓을 수 있는지·맞는 수)은 직접 적지 않고 규칙 엔진에서 계산한다 → 데이터와 규칙이 어긋날 수 없음.
// **굵게** 표시는 화면에서 강조, 읽어 주기에서는 그냥 읽는다.
// 자리표시: {libs} 숨구멍 수, {area}·{warea} 까망이·하양이 집, {stones} 까망이 돌 수, {total} 까망이 돌+집.
// 좌표 [x, y]는 왼쪽 위가 [0, 0]. 강마다 바둑판 크기(size)가 다르다: 작은 판에서 시작해 차츰 9줄로.

export type XY = [number, number];

export interface Setup {
  b?: XY[];
  w?: XY[];
  /** 배치 뒤 흑부터 번갈아 엔진으로 둘 수(되따기 금지처럼 '이전 판'을 기억해야 할 때) */
  moves?: XY[];
}

interface Base {
  text: string;
  setup?: Setup;
  /** 점선 동그라미로 강조할 점 */
  rings?: XY[];
  /** '아니에요' 표시 */
  crosses?: XY[];
  /** {libs} 계산 대상 돌, 그리고 '숨구멍 보여주기'를 켜면 그 숨구멍에 동그라미 */
  libsOf?: XY;
  showLibs?: boolean;
  /** choice의 answer 'legal'에서 '여기에 놓을 수 있나'를 엔진으로 물어볼 점(동그라미로도 표시) */
  probe?: XY;
  /** 'w'면 하양이 차례로 판을 만든다(하양이가 놓을 수 있나 묻기) */
  as?: 'w';
  /** 집 표시(까망이 집 ■, 하양이 집 □). territory 단계에서는 다 찾은 뒤에만 */
  showOwner?: boolean;
  /** move goal 'connect': libsOf 돌과 이어져야 하는 돌 */
  join?: XY;
  /** move goal 'cut': 끊어야 하는 하양이 돌 두 개 */
  cut?: [XY, XY];
}

/**
 * move 단계에서 맞는 수의 조건 — 정답 점은 엔진이 판 전체를 시험해 찾는다.
 *  capture: 하양이 돌을 잡는 수
 *  atari: 둔 뒤 옆의 하양이 돌이 숨구멍 하나(단수)가 되는 수
 *  escape: 둔 뒤 libsOf 까망이 무리의 숨구멍이 2개 이상이 되는 수(늘기·잡기 모두)
 *  connect: 둔 뒤 libsOf 돌과 join 돌이 한 무리가 되는 수
 *  cut: 하양이가 두면 cut 두 돌이 이어지는 자리(그 자리를 까망이가 먼저 차지)
 *  live: 둔 뒤 libsOf 무리의 숨구멍이 2개 이상이고, 하양이가 그 어디에도 놓을 수 없음(눈 두 개)
 */
export type MoveGoal = 'capture' | 'atari' | 'escape' | 'connect' | 'cut' | 'live';

export type Step =
  | (Base & { kind: 'explain' })
  | (Base & {
      kind: 'tap';
      /** 눌러야 하는 점 */
      targets: XY[];
      need: 'one' | 'all';
      /** 누르면 흑돌을 놓아 보여줌 */
      place: boolean;
      done: string;
      wrong: string;
    })
  | (Base & { kind: 'liberties'; libsOf: XY; done: string; wrong: string })
  | (Base & {
      kind: 'choice';
      options: string[];
      /**
       * 정답 번호, 또는 엔진으로 계산:
       * 'libs' 숨구멍 수 · 'area' 까망이 집 수 · 'total' 까망이 돌+집 수 (보기 글의 숫자와 맞춤),
       * 'more' 집이 많은 쪽(0 까망이, 1 하양이), 'turn' 다음 차례(0 까망이, 1 하양이),
       * 'legal' probe 점에 지금 차례가 놓을 수 있나(0 놓을 수 있어요, 1 놓을 수 없어요)
       */
      answer: number | 'libs' | 'area' | 'total' | 'more' | 'turn' | 'legal';
      done: string;
      wrong: string;
    })
  /** 흑돌을 직접 놓아 보기 — 놓으면 엔진이 둔 결과(잡힌 돌 들어내기)를 그대로 보여줌 */
  | (Base & { kind: 'move'; goal: MoveGoal; done: string; wrong: string })
  /** 숨구멍이 하나 남은(단수) 하양이 돌 무리를 모두 찾아 누르기 */
  | (Base & { kind: 'find'; done: string; wrong: string })
  /** 까망이 집(까망이 돌로만 둘러싸인 빈 점)을 모두 찾아 누르기 */
  | (Base & { kind: 'territory'; done: string; wrong: string })
  | (Base & { kind: 'free'; rounds: number; done: string });

